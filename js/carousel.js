// 
// НАЗНАЧЕНИЕ СУЩНОСТИ:
// Этот файл содержит логику бесконечной горизонтальной карусели (бегущей строки) 
// с логотипами партнёров на странице "О компании" (/about.html).
// 
// Карусель работает полностью на клиенте:
// - Загружает список партнёров из data/partners.json.
// - Динамически создаёт <img> для каждого.
// - Дублирует содержимое для эффекта бесконечности.
// - Использует requestAnimationFrame для плавной анимации (не CSS transition или setInterval).
// - Поддерживает паузу при наведении мыши или касании (для удобства чтения).
// - Уважает настройку пользователя "prefers-reduced-motion" (отключает анимацию для людей с чувствительностью к движению).
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// - Подключается ТОЛЬКО на about.html (в конце body, после main.js и modal.js).
// - Ничего не экспортирует и не зависит от других JS-модулей проекта (кроме стандартных браузерных API).
// - Не вызывает addToCart, loadProducts или другие функции.
// - Полностью автономный модуль для визуального эффекта.
// 
// ЗАДАЧА, КОТОРУЮ РЕШАЕТ:
// Создать приятный, профессиональный визуальный элемент "Бренды-партнёры",
// который бесконечно прокручивается, но не отвлекает и не нагружает CPU.
// Сделать его доступным (ARIA, reduced motion) и отказоустойчивым.
// 
// ОСОБЕННОСТИ РЕАЛИЗАЦИИ:
// - Асинхронная функция startPartnersCarousel с try...catch.
// - Использование for...of для создания DOM-элементов.
// - Классический "infinite scroll hack": дублирование контента + сброс позиции.
// - requestAnimationFrame вместо setInterval (более плавно и энергоэффективно).
// - Простая физика: position += speed каждый кадр.
// - Обработка ошибок сети/JSON с fallback-сообщением.
// - Ранние возвраты при отсутствии элемента или отключённой анимации.
// 
// ВЗАИМОСВЯЗЬ С ДРУГИМИ ЧАСТЯМИ:
// - Зависит от: fetch, matchMedia, requestAnimationFrame, DOM API.
// - Использует файл data/partners.json (массив объектов {src, alt}).
// - about.html предоставляет контейнер: <div class="partners__track"></div>.
// - CSS (вероятно в style.css или catalog.css) задаёт overflow, ширину и т.д.
// - Не взаимодействует с корзиной, каталогом или формами.
// 
// УРОВЕНЬ ДЕТАЛИЗАЦИИ ДЛЯ СТУДЕНТОВ:
// Комментарии объясняют:
// - что такое requestAnimationFrame и почему он лучше setInterval;
// - как работает "бесконечная" карусель через дублирование;
// - что такое prefers-reduced-motion и зачем его уважать;
// - разницу между синхронным и асинхронным кодом;
// - как браузер планирует отрисовку кадров;
// - обработку ошибок в асинхронном коде;
// - создание элементов через createElement vs innerHTML.
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Асинхронная функция запуска карусели партнёров.
 * 
 * НАЗНАЧЕНИЕ:
 * Полностью инициализирует и запускает бесконечную горизонтальную карусель
 * с логотипами партнёров. Выполняет все шаги: проверка элемента, проверка reduced-motion,
 * загрузка данных, создание DOM, дублирование, настройка анимации, обработчики паузы.
 * 
 * КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
 * Не принимает параметров.
 * 
 * КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
 * Ничего (Promise, который никогда не используется вызывающим кодом).
 * 
 * КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
 * Вызывается один раз в обработчике DOMContentLoaded в самом низу файла:
 *   document.addEventListener("DOMContentLoaded", startPartnersCarousel);
 * 
 * ЗАДАЧА:
 * Сделать раздел "Бренды-партнёры" на странице about.html живым и профессиональным.
 * 
 * ОСОБЕННОСТИ:
 * - Вся функция async, потому что использует await fetch и await response.json().
 * - Много ранних возвратов (early returns) для разных сценариев отказа.
 * - Вложенная функция animate(), которая рекурсивно вызывает сама себя через requestAnimationFrame.
 * - Использует замыкание: переменные position, isPaused, speed видны внутри animate и обработчиков.
 */
async function startPartnersCarousel() {
  // 1. Находим элемент-контейнер для карусели
  // document.querySelector — ищет первый элемент по CSS-селектору в DOM.
  // Селектор ".partners__track" соответствует <div class="partners__track"> в about.html.
  const track = document.querySelector(".partners__track");

  // Если элемента нет на странице — просто прекращаем работу скрипта
  // Это может случиться, если скрипт подключён на другой странице по ошибке,
  // или если HTML-разметка была изменена.
  // Ранний возврат экономит ресурсы и избегает ошибок.
  if (!track) return;

  // Проверяем, не отключил ли пользователь анимации в настройках своей ОС
  // 
  // matchMedia — глобальный метод (window.matchMedia).
  // Принимает медиа-запрос в виде строки (точно как в CSS @media).
  // Возвращает объект MediaQueryList.
  // 
  // .matches — свойство, boolean: true если текущие настройки устройства/браузера
  // удовлетворяют запросу.
  // 
  // "(prefers-reduced-motion: reduce)" — стандартный медиа-запрос,
  // который пользователь может включить в ОС (Windows, macOS, iOS и т.д.)
  // для уменьшения анимаций (например, при вестибулярных нарушениях, эпилепсии и т.д.).
  // 
  // УВАЖЕНИЕ ЭТОГО НАСТРОЕНИЯ — требование современного веб (WCAG, inclusive design).
  const prefersReducedMotion = matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (prefersReducedMotion) return;

  // Блок try...catch оборачивает всю асинхронную работу с сетью и DOM.
  // Если что-то пойдёт не так (нет интернета, файл partners.json удалён,
  // сервер вернул ошибку, JSON повреждён) — мы попадём в catch и покажем fallback.
  try {
    // 2. Загружаем список партнеров из файла
    // fetch — встроенный браузерный метод для HTTP-запросов (см. подробное объяснение в data.js).
    // "./data/partners.json" — относительный путь (от текущей страницы about.html).
    // await — приостанавливает выполнение функции до получения ответа.
    const response = await fetch("./data/partners.json");

    // response.json() — читает тело ответа и парсит как JSON.
    // await — ждём завершения парсинга.
    const partners = await response.json();

    // 3. Проходимся по каждому партнеру и создаем для него HTML-элементы
    // 
    // for...of — современный цикл для итерации по итерируемым объектам (массивам, строкам, NodeList и т.д.).
    // 
    // for (const partner of partners) — на каждой итерации partner = очередной элемент массива.
    // Это удобнее классического for (let i = 0; i < partners.length; i++), потому что не нужно работать с индексами.
    for (const partner of partners) {
      // if (!partner.src) continue;
      // continue — ключевое слово цикла: "пропусти оставшуюся часть тела цикла и перейди к следующей итерации".
      // Здесь: если у партнёра нет свойства src (или оно пустое/falsy) — пропускаем его.
      // Защита от неполных данных в JSON.
      if (!partner.src) continue; // Пропускаем, если нет картинки

      // Создаём новый <div> в памяти (ещё не на странице).
      // document.createElement("div") — стандартный способ создания элементов через JS.
      // Альтернатива: innerHTML, но createElement безопаснее и быстрее для единичных элементов.
      const item = document.createElement("div");
      item.className = "partners__item";

      // Создаём <img>.
      const img = document.createElement("img");

      // Устанавливаем атрибуты src и alt.
      // img.src = ... — браузер начнёт загрузку изображения асинхронно.
      // img.alt = ... — важно для доступности (скринридеры) и SEO.
      // partner.alt || "Партнер" — если alt отсутствует в JSON, используем запасной текст.
      img.src = partner.src;
      img.alt = partner.alt || "Партнер";

      // Добавляем img внутрь item.
      // element.appendChild(child) — добавляет child как последнего потомка.
      item.appendChild(img);

      // Добавляем готовый item внутрь track.
      // Теперь картинка появится на странице (браузер отрисует её).
      track.appendChild(item);
    }

    // 4. Хитрость для бесконечной прокрутки:
    // Просто копируем всё содержимое и вставляем его же в конец.
    // Теперь у нас два одинаковых списка подряд.
    // 
    // track.innerHTML += track.innerHTML;
    // 
    // innerHTML — свойство, которое при чтении возвращает HTML-разметку всего содержимого как строку.
    // При записи — полностью заменяет содержимое (парсит строку как HTML).
    // 
    // Операция += конкатенирует текущий HTML с самим собой.
    // Результат: track теперь содержит оригинальные элементы + точную копию.
    // 
    // ПОЧЕМУ ЭТО РАБОТАЕТ ДЛЯ БЕСКОНЕЧНОСТИ:
    // Позже в анимации мы будем двигать track влево.
    // Когда мы дойдём до середины (конца первого списка), мы мгновенно сбрасываем position в 0.
    // Пользователь видит seamless переход, потому что второй список идентичен первому.
    // Это классический "infinite marquee" hack без дублирования данных в JS.
    track.innerHTML += track.innerHTML;

    // 5. Настройка анимации
    // 
    // Эти три переменные объявлены с let, потому что их значения будут меняться
    // во время работы анимации. Они "замыкаются" (closure) внутри функции animate()
    // и обработчиков событий — т.е. animate видит актуальные значения position и isPaused.
    let position = 0; // Текущая позиция прокрутки
    let isPaused = false; // Флаг паузы
    const speed = 0.5; // Скорость (пиксели за кадр)

    // Вложенная функция animate — "сердце" анимации.
    // Она будет вызываться браузером перед каждым кадром отрисовки.
    function animate() {
      // Если не на паузе — двигаем позицию.
      if (!isPaused) {
        // Увеличиваем позицию на скорость.
        // position становится всё больше и больше (track уезжает влево).
        position += speed;

        // Если мы прокрутили ровно половину всей длины (то есть первый оригинальный список)
        // Мы незаметно сбрасываем позицию в 0 (в начало).
        // Глаз этого не заметит, так как списки идентичны.
        // 
        // track.scrollWidth — свойство Element.
        // Возвращает полную ширину содержимого элемента, включая то, что не видно (overflow).
        // После дублирования scrollWidth = 2 × ширина_одного_списка.
        // Поэтому / 2 — это ширина одного полного прохода.
        if (position >= track.scrollWidth / 2) {
          position = 0;
        }

        // Сдвигаем контейнер влево с помощью CSS transform.
        // 
        // element.style.transform = `translateX(-${position}px)`;
        // 
        // style — объект, через который можно читать/писать инлайн-стили элемента.
        // transform: translateX(...) — очень эффективная операция для анимации
        // (использует GPU, не вызывает reflow всего документа).
        // 
        // Шаблонная строка с ${position} — каждый кадр мы генерируем новую строку
        // вида "translateX(-123.45px)".
        track.style.transform = `translateX(-${position}px)`;
      }

      // Просим браузер вызвать эту же функцию перед отрисовкой следующего кадра
      // 
      // requestAnimationFrame(callback):
      // Глобальный метод (на window).
      // 
      // ЧТО ЭТО ТАКОЕ:
      // Это способ сказать браузеру: "Перед тем, как ты в следующий раз перерисуешь экран,
      // вызови вот эту функцию".
      // 
      // Браузер обычно старается делать 60 кадров в секунду (16.6 мс на кадр).
      // requestAnimationFrame синхронизируется с этим ритмом.
      // 
      // ПОЧЕМУ ЛУЧШЕ setInterval или setTimeout:
      // - setInterval(animate, 16) будет вызывать функцию каждые 16мс,
      //   даже если вкладка невидима, или браузер занят, или пользователь прокручивает.
      //   Это тратит CPU зря и может вызывать "jank" (рывки).
      // - requestAnimationFrame:
      //   * Вызывается только когда браузер готов рисовать.
      //   * Автоматически приостанавливается, когда вкладка неактивна.
      //   * Браузер может оптимизировать (например, снизить частоту на слабых устройствах).
      //   * Передаёт в callback высокоточное время (timestamp), хотя мы его здесь не используем.
      // 
      // ВЫЗОВ В КОНЦЕ:
      // animate вызывает requestAnimationFrame(animate) — это создаёт бесконечный цикл,
      // который продолжается, пока страница открыта.
      // Это и есть "игровой цикл" или "animation loop".
      requestAnimationFrame(animate);
    }

    // 6. Ставим на паузу, когда пользователь наводит мышку или касается экрана
    // 
    // addEventListener — стандартный способ подписки на события (см. подробное объяснение в main.js).
    // 
    // "mouseenter" — событие, когда курсор мыши входит в область элемента.
    // "mouseleave" — когда покидает.
    // 
    // "touchstart" / "touchend" — аналоги для сенсорных экранов (мобильные, планшеты).
    // 
    // Стрелочные функции-обработчики очень короткие — они просто меняют флаг isPaused.
    // Когда isPaused === true, код внутри animate() пропускает движение (position не меняется).
    track.addEventListener("mouseenter", () => (isPaused = true));
    track.addEventListener("mouseleave", () => (isPaused = false));
    track.addEventListener("touchstart", () => (isPaused = true));
    track.addEventListener("touchend", () => (isPaused = false));

    // 7. Запускаем анимацию
    // Первый вызов requestAnimationFrame(animate) запускает цикл.
    // Дальше animate будет вызывать сама себя.
    animate();
  } catch (error) {
    // Если произошла ошибка (например, нет интернета или файла)
    // 
    // console.error — метод глобального объекта console.
    // Выводит сообщение в консоль разработчика (красным цветом, со стеком).
    // Полезно для отладки, но не показывается обычному пользователю.
    console.error("Не удалось загрузить карусель:", error);

    // Показываем пользователю понятное сообщение внутри контейнера карусели.
    // innerHTML = строка — заменяем всё содержимое track на div с текстом.
    // Стили: inline style (color: gray) — для простоты, без добавления CSS-класса.
    track.innerHTML = '<div style=\"color: gray;\">Не удалось загрузить список партнёров</div>';
  }
}

// Запускаем скрипт только когда вся страница (HTML) полностью загрузилась
// 
// document.addEventListener("DOMContentLoaded", ...)
// 
// Это критично: мы используем document.querySelector(".partners__track").
// Если запустить код раньше (например, скрипт в <head>), элемент ещё может не существовать в DOM,
// и track будет null.
// 
// DOMContentLoaded наступает после того, как браузер разобрал весь HTML и создал дерево элементов,
// но до загрузки изображений и других внешних ресурсов.
// Идеальный момент для инициализации JS, который работает с DOM.
document.addEventListener("DOMContentLoaded", startPartnersCarousel);
