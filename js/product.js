// ═══════════════════════════════════════════════════════════════════════════════
// МОДУЛЬ: product.js
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ СУЩНОСТИ:
// Этот файл содержит всю логику страницы отдельного товара (/product.html?id=...).
// Он отвечает за:
// - Чтение параметра id из URL (query string).
// - Загрузку всех товаров через loadProducts() из data.js.
// - Поиск конкретного товара по id.
// - Если товар не найден — редирект на каталог.
// - Заполнение всей страницы данными товара (название, цена, характеристики, описание, изображения, наличие).
// - Обновление заголовка вкладки браузера (document.title).
// - Обработку клика на кнопку "В корзину" (вызов addToCart).
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// - Подключается только на product.html (после main.js, modal.js, data.js).
// - Вызывает loadProducts() из data.js.
// - Вызывает addToCart() из main.js.
// - Использует currentProduct как временное хранилище выбранного товара.
// - Не зависит от catalog.js или cart.js напрямую.
// 
// ЗАДАЧА, КОТОРУЮ РЕШАЕТ:
// Показать детальную карточку одного компьютера со всеми характеристиками.
// Позволить пользователю добавить именно этот товар в корзину прямо со страницы товара.
// Обеспечить graceful fallback, если id в URL неверный.
// 
// ОСОБЕННОСТИ РЕАЛИЗАЦИИ:
// - Использует URLSearchParams — современный и удобный API для парсинга query string.
// - Асинхронная инициализация (async/await).
// - Много селекторов по data-атрибутам ([data-product-title], [data-spec-cpu] и т.д.).
// - Object.entries + forEach для заполнения характеристик (динамический маппинг).
// - Ранний редирект при отсутствии товара.
// - Глобальная переменная currentProduct, чтобы кнопка "В корзину" могла получить актуальный товар.
// - Кнопка добавления в корзину ищется сразу при загрузке скрипта (до DOMContentLoaded), но обработчик вешается безопасно.
// 
// ВЗАИМОСВЯЗЬ С ДРУГИМИ ЧАСТЯМИ:
// - Зависит от: loadProducts (data.js), addToCart (main.js).
// - product.html предоставляет разметку с data-атрибутами и placeholder'ами ("Загрузка", "Карточка товара").
// - При успешной загрузке заменяет текст и атрибуты.
// - После добавления в корзину — работает точно так же, как из каталога (badge обновляется, toast показывается).
// 
// УРОВЕНЬ ДЕТАЛИЗАЦИИ ДЛЯ СТУДЕНТОВ:
// Подробно объясняется:
// - что такое URL query parameters и как их читать в браузере;
// - разница между window.location.search и URLSearchParams;
// - зачем нужен async/await на странице товара;
// - как data-атрибуты используются для "связи" HTML и JS без жёстких id;
// - Object.entries как способ итерации по объектам;
// - почему currentProduct хранится глобально;
// - редирект через window.location.href;
// - порядок выполнения кода (синхронный поиск кнопки + асинхронная загрузка данных).
// ═══════════════════════════════════════════════════════════════════════════════

// ═══════════════════════════════════════════════════════════════════════════════
// ГЛОБАЛЬНАЯ ПЕРЕМЕННАЯ
// ═══════════════════════════════════════════════════════════════════════════════

// let currentProduct = null;
// 
// Хранит объект текущего отображаемого товара.
// 
// Инициализируется в null.
// Устанавливается в fillProduct(product).
// 
// ЗАЧЕМ НУЖНА:
// Кнопка "В корзину" ([data-product-add]) ищется синхронно при загрузке скрипта (ещё до того,
// как данные товара загрузились). Обработчик клика проверяет if (currentProduct),
// потому что на момент клика данные уже должны быть загружены (пользователь видит страницу).
// 
// Это простой способ "передать" данные из асинхронной initProductPage в обработчик клика,
// без замыкания или более сложных паттернов.
let currentProduct = null;

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: formatProductPrice(price)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Форматирует цену товара точно так же, как formatPrice в catalog.js и formatCartPrice в cart.js.
// Выделена в отдельную функцию для независимости модуля product.js.
// 
// ПРИМЕР: 235000 → "235 000 ₽"
// 
// ИСПОЛЬЗУЕТСЯ ТОЛЬКО В: fillProduct().
function formatProductPrice(price) {
  // Number(price) — на случай строки.
  // toLocaleString("ru-RU") — добавляет пробелы как разделители тысяч.
  // Шаблонная строка + ₽.
  return `${Number(price).toLocaleString('ru-RU')} ₽`;
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: fillProduct(product)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Заполняет ВСЮ страницу продукта реальными данными из объекта товара.
// Обновляет:
// - document.title (заголовок вкладки браузера);
// - src и alt главной картинки;
// - src и alt всех миниатюр (thumbs);
// - название, хлебные крошки, бренд, цену, наличие, описание;
// - характеристики (CPU, RAM, GPU, Storage) через data-атрибуты.
// 
// Сохраняет товар в currentProduct для кнопки корзины.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// product — объект товара (с полями title, brand, price, image, stock, description, specs и т.д.).
// 
// ВОЗВРАЩАЕТ:
// Ничего (побочные эффекты на DOM и document.title).
// 
// ВЫЗЫВАЕТСЯ ИЗ: initProductPage() после успешного поиска товара.
function fillProduct(product) {
  // Сохраняем ссылку на товар в глобальную переменную.
  // Это нужно, чтобы позже (при клике на кнопку) мы могли передать его в addToCart.
  currentProduct = product;

  // Обновляем заголовок вкладки браузера.
  // document.title — свойство глобального объекта document.
  // Браузер показывает это значение в заголовке вкладки и в истории.
  // Шаблон: "MSI Titan Pro X12 — ООО Интерриум"
  document.title = `${product.title} — ООО Интерриум`;

  // === ПОИСК ЭЛЕМЕНТОВ ПО СЕЛЕКТОРАМ ===
  // Мы используем как классы (.product-detail__image), так и data-атрибуты ([data-product-title]).
  // data-атрибуты удобны, когда один и тот же элемент может иметь разное значение в зависимости от страницы,
  // и мы не хотим плодить уникальные классы.

  const image = document.querySelector('.product-detail__image');
  const title = document.querySelector('[data-product-title]');
  const breadcrumb = document.querySelector('[data-product-breadcrumb]');
  const brand = document.querySelector('[data-product-brand]');
  const price = document.querySelector('[data-product-price]');
  const stock = document.querySelector('[data-product-stock]');
  const description = document.querySelector('[data-product-description]');

  // === ЗАПОЛНЕНИЕ ГЛАВНОГО ИЗОБРАЖЕНИЯ ===
  // Проверяем, что элемент существует (if (image)), чтобы не было ошибок,
  // если разметка в product.html изменится.
  if (image) {
    image.src = product.image;   // меняем адрес картинки
    image.alt = product.title;   // обновляем альтернативный текст
  }

  // === ЗАПОЛНЕНИЕ МИНИАТЮР (THUMBS) ===
  // document.querySelectorAll — находит ВСЕ элементы, соответствующие селектору.
  // Возвращает NodeList (похож на массив).
  // 
  // .forEach((thumb) => { ... }) — метод NodeList (и Array).
  // Выполняет функцию для каждого найденного миниатюрного изображения.
  // 
  // Мы устанавливаем всем миниатюрам тот же src и alt, что и главной картинке.
  // (В реальном проекте миниатюры могли бы быть разными, но здесь для простоты — одна и та же картинка).
  document.querySelectorAll('.product-detail__thumbs img').forEach((thumb) => {
    thumb.src = product.image;
    thumb.alt = `Миниатюра ${product.title}`;
  });

  // === ЗАПОЛНЕНИЕ ТЕКСТОВЫХ ПОЛЕЙ ===
  // if (title) — защита.
  // .textContent = ... — заменяет текстовое содержимое элемента (безопасно, не интерпретирует HTML).
  if (title) title.textContent = product.title;
  if (breadcrumb) breadcrumb.textContent = product.title;
  if (brand) brand.textContent = `Бренд: ${product.brand}`;
  if (price) price.textContent = formatProductPrice(product.price);
  if (description) description.textContent = product.description;

  // === ЗАПОЛНЕНИЕ СТАТУСА НАЛИЧИЯ ===
  if (stock) {
    // Тернарный оператор: если product.stock === true — "В наличии", иначе "Под заказ".
    stock.textContent = product.stock ? 'В наличии' : 'Под заказ';

    // Обновляем класс badge динамически.
    // className = ... — полностью перезаписывает атрибут class.
    // Используем шаблонную строку, чтобы добавить badge--success или badge--muted.
    stock.className = `badge ${product.stock ? 'badge--success' : 'badge--muted'}`;
  }

  // === ЗАПОЛНЕНИЕ ХАРАКТЕРИСТИК (SPECS) ===
  // 
  // Создаём объект-мап (map) соответствия: CSS-селектор → значение из product.specs.
  // Это удобный способ избежать повторяющегося кода для 4 характеристик.
  const specMap = {
    '[data-spec-cpu]': product.specs.CPU,
    '[data-spec-ram]': product.specs.RAM,
    '[data-spec-gpu]': product.specs.GPU,
    '[data-spec-storage]': product.specs.Storage,
  };

  // Object.entries(specMap) — статический метод глобального объекта Object.
  // 
  // ПРИНИМАЕТ: объект.
  // ВОЗВРАЩАЕТ: массив пар [ключ, значение].
  // Пример: [ ['[data-spec-cpu]', 'Intel i7'], ['[data-spec-ram]', '16GB'], ... ]
  // 
  // Это позволяет итерировать одновременно по селектору и по значению.
  // 
  // .forEach(([selector, value]) => { ... })
  // Деструктуризация в параметрах forEach: каждый элемент массива — это подмассив из двух элементов.
  // [selector, value] "распаковывает" их в две отдельные переменные.
  Object.entries(specMap).forEach(([selector, value]) => {
    // Ищем элемент по селектору (например, <dd data-spec-cpu></dd>).
    const el = document.querySelector(selector);
    // Если нашли — записываем значение.
    if (el) el.textContent = value;
  });
}

// ═══════════════════════════════════════════════════════════════════════════════
// АСИНХРОННАЯ ФУНКЦИЯ ИНИЦИАЛИЗАЦИИ СТРАНИЦЫ
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Асинхронная функция инициализации страницы товара.
 * 
 * НАЗНАЧЕНИЕ:
 * 1. Читает параметр ?id= из URL.
 * 2. Загружает все товары.
 * 3. Ищет товар с нужным id.
 * 4. Если не найден — перенаправляет на каталог.
 * 5. Если найден — заполняет страницу через fillProduct.
 * 
 * ВЫЗЫВАЕТСЯ:
 * document.addEventListener("DOMContentLoaded", initProductPage);
 * 
 * ПОЧЕМУ async:
 * Потому что нужно дождаться загрузки данных: const products = await loadProducts();
 */
async function initProductPage() {
  // === ЧТЕНИЕ ПАРАМЕТРОВ URL ===
  // 
  // window.location — объект, описывающий текущий адрес страницы.
  // .search — часть URL после ? (query string), например "?id=5&foo=bar".
  // 
  // new URLSearchParams(window.location.search):
  // Конструктор URLSearchParams принимает строку query и превращает её в удобный объект.
  // 
  // Пример:
  // URL: product.html?id=42&foo=bar
  // params.get('id') → "42"
  // params.get('foo') → "bar"
  // params.has('id') → true
  // 
  // Это гораздо удобнее, чем вручную парсить строку через split('&') и т.д.
  const params = new URLSearchParams(window.location.search);

  // Получаем значение параметра 'id'.
  // params.get('id') возвращает строку или null.
  // parseInt(..., 10) — превращает строку в целое число (второй аргумент — система счисления, 10 = десятичная).
  // Если id нет в URL — parseInt(null, 10) даст NaN.
  const id = parseInt(params.get('id'), 10);

  // === ЗАГРУЗКА ДАННЫХ ===
  // Вызываем loadProducts из data.js.
  // await — ждём, пока данные придут (или вернётся [] при ошибке).
  const products = await loadProducts();

  // === ПОИСК ТОВАРА ===
  // Array.prototype.find — ищет первый элемент, удовлетворяющий условию.
  // Возвращает товар или undefined.
  // 
  // (item) => item.id === id
  // Сравнение строгое ===. id из URL мы привели к числу, id в JSON — тоже числа.
  const product = products.find((item) => item.id === id);

  // === ОБРАБОТКА ОТСУТСТВИЯ ТОВАРА ===
  if (!product) {
    // Товар не найден (неверный id, или данные не загрузились).
    // window.location.href = '...' — свойство location.
    // Присваивание нового значения вызывает навигацию браузера (переход на другую страницу).
    // Пользователь будет перенаправлен на каталог.
    window.location.href = 'catalog.html';
    return; // выходим, чтобы не выполнять fillProduct
  }

  // === УСПЕХ ===
  // Заполняем страницу.
  fillProduct(product);
}

// ═══════════════════════════════════════════════════════════════════════════════
// ОБРАБОТЧИК КНОПКИ "В КОРЗИНУ"
// ═══════════════════════════════════════════════════════════════════════════════

// Ищем кнопку добавления в корзину ПОСЛЕ объявления функций, но ДО DOMContentLoaded.
// 
// document.querySelector('[data-product-add]') — выполняется сразу при парсинге этого скрипта.
// На момент выполнения product.html уже полностью загружен (скрипт в конце <body>),
// поэтому элемент уже существует.
const addButton = document.querySelector('[data-product-add]');

// Если кнопка существует — вешаем на неё обработчик клика.
if (addButton) {
  addButton.addEventListener('click', () => {
    // Проверяем, что товар уже загружен и сохранён в currentProduct.
    // Это может быть false только в очень редком случае гонки (пользователь кликнул до завершения загрузки),
    // но благодаря await в initProductPage и DOMContentLoaded это практически исключено.
    if (currentProduct) {
      // Вызываем общую функцию добавления из main.js.
      // Она сохранит в localStorage, обновит badge и покажет toast.
      addToCart(currentProduct);
    }
  });
}

// ═══════════════════════════════════════════════════════════════════════════════
// ЗАПУСК
// ═══════════════════════════════════════════════════════════════════════════════

// Когда DOM готов — запускаем асинхронную инициализацию страницы товара.
// Обратите внимание: поиск кнопки выше происходит раньше этого события,
// но сама загрузка данных и заполнение — только после DOMContentLoaded.
document.addEventListener('DOMContentLoaded', initProductPage);
