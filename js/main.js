// ФУНКЦИЯ: initHeaderScroll()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Настраивает динамическое изменение внешнего вида шапки при прокрутке страницы.
// Когда пользователь прокручивает вниз больше чем на 4 пикселя — добавляется класс "header--scrolled".
// CSS использует этот класс для изменения фона, тени, размера и т.д. (эффект "прилипания"/"сжатия").
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Ничего.
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Ничего.
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Вызывается один раз при загрузке страницы из DOMContentLoaded обработчика внизу этого файла.
// Работает на всех страницах, где есть .header (все).
// 
// ЗАДАЧА:
// Улучшить визуальное восприятие: шапка "реагирует" на прокрутку, выглядит современно.
// 
// ОСОБЕННОСТИ:
// - Ранний возврат, если .header не найден.
// - Использует window.scrollY.
// - Добавляет слушатель события "scroll" с опцией { passive: true }.
// - Определяет вложенную стрелочную функцию setScrolled и вызывает её сразу.
// 
// ВЗАИМОСВЯЗЬ:
// - Манипулирует DOM: header.classList.toggle.
// - Слушает: window "scroll" событие.
function initHeaderScroll() {
  // Ищем элемент шапки по классу.
  const header = document.querySelector(".header");

  // Если шапки нет на странице — выходим сразу.
  // if (!header) return; — ранний возврат. Избегаем лишней вложенности кода.
  if (!header) return; // Ранний выход, не плодим вложенность

  // Определяем стрелочную функцию setScrolled.
  // Она будет вызываться при каждом событии scroll.
  // 
  // Стрелочная функция () => { ... } — современный способ объявления функций (ES6).
  // Не имеет собственного this (берёт из окружающего контекста).
  // Короткий синтаксис.
  const setScrolled = () => {
    // header.classList.toggle(className, force):
    // Метод DOMTokenList.
    // 
    // ПАРАМЕТРЫ:
    //   className — строка.
    //   force (необязательный) — boolean.
    // 
    // ПОВЕДЕНИЕ:
    // Если force не передан — переключает класс: если есть — удаляет, если нет — добавляет.
    // Если force === true — всегда добавляет.
    // Если force === false — всегда удаляет.
    // 
    // ЗДЕСЬ:
    // window.scrollY — свойство window (или document.documentElement.scrollTop в старых браузерах).
    // Возвращает количество пикселей, на которое документ прокручен по вертикали.
    // 
    // Условие: window.scrollY > 4
    // Если прокручено больше 4px — добавляем класс "header--scrolled".
    // Иначе (при возврате вверх) — удаляем.
    // 
    // 4 пикселя — очень маленькое значение. Сделано, чтобы класс добавлялся почти сразу при начале скролла.
    header.classList.toggle("header--scrolled", window.scrollY > 4);
  };

  // Подписываемся на событие "scroll" на объекте window.
  // 
  // window.addEventListener(type, listener, options):
  // Метод EventTarget (window, document, элементы и т.д. наследуют).
  // 
  // ЧТО ТАКОЕ СОБЫТИЕ (EVENT) В БРАУЗЕРЕ:
  // Событие — это объект, который браузер создаёт, когда происходит что-то интересное:
  // пользователь кликнул, прокрутил, нажал клавишу, загрузился ресурс, изменился размер окна и т.д.
  // 
  // МЕХАНИЗМ ПОДПИСКИ (addEventListener):
  // Мы говорим браузеру: "Когда произойдёт событие типа 'scroll', вызови вот эту функцию (setScrolled)".
  // Функция, которую мы передаём, называется "обработчиком события" (event handler / event listener).
  // 
  // ПАРАМЕТРЫ:
  //   type — строка, тип события ("click", "scroll", "input", "keydown", "DOMContentLoaded" и т.д.).
  //   listener — функция, которая будет вызвана. Получает один аргумент — объект события (event).
  //   options (необязательный) — объект или boolean. Здесь мы передаём объект { passive: true }.
  // 
  // ОПЦИЯ { passive: true }:
  // Сообщает браузеру, что наш обработчик НЕ будет вызывать event.preventDefault().
  // Это позволяет браузеру сразу начинать прокрутку, не дожидаясь выполнения JS.
  // Улучшает производительность (особенно на мобильных) и убирает предупреждения в консоли.
  // 
  // КОГДА ВЫЗЫВАЕТСЯ ОБРАБОТЧИК:
  // Браузерный движок (обычно несколько раз в секунду во время прокрутки) вызывает setScrolled.
  // Внутри setScrolled мы читаем window.scrollY и меняем класс.
  // 
  // АЛЬТЕРНАТИВЫ:
  // Можно было бы использовать onscroll = setScrolled (старый способ, только один обработчик).
  // addEventListener позволяет добавлять несколько обработчиков на одно событие.
  // 
  // window.addEventListener("scroll", setScrolled, { passive: true });
  window.addEventListener("scroll", setScrolled, { passive: true });

  // Вызываем setScrolled() сразу после подписки.
  // Это нужно, чтобы при загрузке страницы (если пользователь уже прокрутил) 
  // класс "header--scrolled" был добавлен сразу, без необходимости ждать первого scroll события.
  setScrolled();
}

