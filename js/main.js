// document.addEventListener("DOMContentLoaded", () => { ... }):
// 
// САМОЕ ВАЖНОЕ СОБЫТИЕ ДЛЯ ИНИЦИАЛИЗАЦИИ.
// 
// ЧТО ТАКОЕ "DOMContentLoaded":
// Это событие, которое браузер генерирует, когда:
// - HTML-документ полностью разобран;
// - все теги созданы в DOM;
// - синхронные скрипты выполнены;
// - но внешние ресурсы (изображения, стили, iframe) ЕЩЁ могут загружаться.
// 
// В отличие от window.onload (или "load"), которое ждёт ВСЁ (включая картинки).
// DOMContentLoaded наступает раньше — это идеальный момент для запуска JS, 
// который манипулирует DOM и не зависит от изображений.
// 
// Почему мы используем именно его:
// В этом скрипте мы ищем .header, .header__burger и т.д.
// Если бы мы запустили код сразу (без ожидания), HTML ещё мог бы не быть разобран,
// и document.querySelector вернул бы null.
// 
// Стрелочная функция без параметров — наш обработчик.
// Внутри мы вызываем три функции инициализации.
document.addEventListener("DOMContentLoaded", () => {
  // Обновляем счётчик корзины в шапке (на случай, если у пользователя уже были товары).
  updateCartBadge();

  // Запускаем логику изменения шапки при скролле.
  initHeaderScroll();

  // Запускаем логику бургер-меню.
  initBurgerMenu();
});
