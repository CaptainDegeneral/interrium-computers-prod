// ФУНКЦИЯ: initBurgerMenu()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Настраивает интерактивное бургер-меню для мобильных устройств.
// По клику на кнопку-бургер открывает/закрывает навигацию (.header__nav).
// Также:
// - Закрывает меню при клике на любую ссылку в меню.
// - Закрывает меню при нажатии клавиши Escape.
// - Блокирует прокрутку body, когда меню открыто (is-locked).
// - Обновляет ARIA-атрибуты для доступности (aria-expanded).
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Ничего.
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Ничего.
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Вызывается один раз при DOMContentLoaded. Работает на всех страницах.
// 
// ЗАДАЧА:
// Сделать навигацию удобной на маленьких экранах (стандартный паттерн "hamburger menu").
// Обеспечить доступность (ARIA).
// 
// ОСОБЕННОСТИ:
// - Несколько ранних возвратов.
// - Две вложенные стрелочные функции: closeMenu и toggleMenu.
// - Использует classList.toggle с boolean-аргументом.
// - Слушает три разных события: click на burger, click на navLinks, keydown на document.
// - Манипулирует несколькими элементами одновременно (burger, nav, body).
function initBurgerMenu() {
  // Ищем три элемента по CSS-селекторам.
  const burger = document.querySelector(".header__burger");
  const nav = document.querySelector(".header__nav");
  const navLinks = document.querySelectorAll(".header__nav-link");

  // Если нет бургера или навигации — выходим (меню не нужно инициализировать).
  if (!burger || !nav) return; // Ранний выход

  // Определяем функцию закрытия меню.
  const closeMenu = () => {
    // Удаляем класс "is-active" с кнопки бургера (обычно меняет иконку на крестик).
    burger.classList.remove("is-active");

    // Устанавливаем aria-expanded="false" — для скринридеров (меню закрыто).
    burger.setAttribute("aria-expanded", "false");

    // Удаляем класс, который показывает навигацию (CSS: .header__nav--open { display: ... }).
    nav.classList.remove("header__nav--open");

    // Удаляем класс с body, который блокировал прокрутку (overflow: hidden в CSS).
    document.body.classList.remove("is-locked");
  };

  // Определяем функцию переключения меню (открыть ↔ закрыть).
  const toggleMenu = () => {
    // nav.classList.toggle("header__nav--open"):
    // Переключает класс. Возвращает boolean: true если класс был добавлен, false если удалён.
    // Сохраняем результат в isOpen.
    const isOpen = nav.classList.toggle("header__nav--open");

    // Синхронно переключаем класс на бургере в зависимости от isOpen.
    // classList.toggle(class, force) — если force=true, добавляет; false — удаляет.
    burger.classList.toggle("is-active", isOpen);

    // Обновляем ARIA-атрибут. String(isOpen) — "true" или "false".
    burger.setAttribute("aria-expanded", String(isOpen));

    // Переключаем блокировку прокрутки на body.
    document.body.classList.toggle("is-locked", isOpen);
  };

  // Подписываемся на событие "click" на кнопке бургера.
  // При клике вызывается toggleMenu.
  // 
  // addEventListener("click", toggleMenu):
  // Когда пользователь кликает на .header__burger, браузер создаёт объект события MouseEvent
  // и вызывает toggleMenu(event). (Мы не используем параметр event внутри toggleMenu).
  burger.addEventListener("click", toggleMenu);

  // Для КАЖДОЙ ссылки в навигации (navLinks — это NodeList, похож на массив)
  // подписываемся на "click".
  // 
  // NodeList.prototype.forEach(callback):
  // Метод, похожий на Array.prototype.forEach.
  // Вызывает callback для каждого элемента коллекции.
  // 
  // (link) => link.addEventListener("click", closeMenu):
  // Для каждой ссылки добавляем обработчик, который при клике закроет меню.
  // Это удобно: пользователь выбрал пункт меню → меню закрылось автоматически.
  navLinks.forEach((link) => link.addEventListener("click", closeMenu));

  // Подписываемся на событие "keydown" на всём документе.
  // Это позволяет ловить нажатие клавиш в любом месте страницы.
  // 
  // document.addEventListener("keydown", (event) => { ... }):
  // 
  // Объект события (event) — здесь KeyboardEvent.
  // Свойство event.key — строка с названием нажатой клавиши ("Escape", "Enter", "a", "ArrowDown" и т.д.).
  // 
  // Если нажата клавиша Escape — вызываем closeMenu().
  // Это стандартное поведение для модальных окон и меню: Esc = закрыть.
  // 
  // ЗАЧЕМ document, а не window:
  // document тоже является EventTarget. События клавиатуры всплывают до document.
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

