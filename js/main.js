// ФУНКЦИЯ: saveCartItems(cart)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Сохраняет переданный массив товаров в localStorage под ключом CART_STORAGE_KEY.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Один параметр: cart — массив объектов товаров (должен быть массивом, но функция не проверяет).
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Ничего (undefined). Функция выполняет побочный эффект (side effect) — запись в хранилище.
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Вызывается из addToCart() после изменения корзины (добавление нового или увеличение quantity).
// Также косвенно влияет на cart.js (хотя cart.js имеет свою saveCart).
// 
// ЗАДАЧА:
// Сделать изменения в корзине постоянными (переживают перезагрузку страницы).
// 
// ОСОБЕННОСТИ:
// - Использует JSON.stringify — обратная операция к JSON.parse.
// - Не делает никакой валидации — доверяет вызывающему коду.
function saveCartItems(cart) {
  // localStorage.setItem(key, value) — метод Storage.
  // Принимает два параметра: строку-ключа и строку-значения.
  // Если ключ уже существует — перезаписывает.
  // 
  // JSON.stringify(cart) — глобальный метод.
  // Принимает любое JavaScript-значение, возвращает строку в формате JSON.
  // Массив объектов превращается в строку вида '[{"id":1,"title":"...","quantity":2}, ...]'.
  // 
  // ЗАЧЕМ НУЖНО:
  // localStorage может хранить только строки (и числа/булевы как строки).
  // Объекты и массивы нужно "сериализовать" (преобразовать в строку).
  // 
  // ВЛИЯНИЕ:
  // После этого вызова данные попадают на диск пользователя.
  // При следующем открытии сайта (даже через неделю) safeParseCart сможет их прочитать.
  localStorage.setItem(CART_STORAGE_KEY, JSON.stringify(cart));
}

