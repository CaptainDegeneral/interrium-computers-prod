// Объявляем константу CART_STORAGE_KEY и присваиваем ей строку "cart".
// 
// ЧТО ТАКОЕ КОНСТАНТА:
// const — ключевое слово для объявления переменной, значение которой НЕЛЬЗЯ переприсвоить после инициализации.
// В отличие от let (можно менять) и var (устаревшее, имеет проблемы с областью видимости).
// 
// ЗАЧЕМ НУЖНА:
// Мы используем одну и ту же строку "cart" в нескольких местах (getItem, setItem).
// Если однажды решим поменять ключ хранения (например, на "user_cart_v2"), 
// достаточно будет изменить только здесь — в одном месте.
// Это называется "единственный источник правды" (Single Source of Truth).
// 
// ТИП ДАННЫХ: string (строка).
// 
// ВЛИЯНИЕ НА ПРОГРАММУ:
// Нигде в коде не используется "жёстко" строка "cart" — только через эту константу.
// Это делает код более поддерживаемым.
const CART_STORAGE_KEY = "cart";

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: safeParseCart()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Безопасно загружает массив товаров из localStorage и возвращает его.
// Если данных нет, или они повреждены, или не являются массивом — возвращает пустой массив [].
// Название "safe" (безопасная) подчёркивает, что функция никогда не бросает ошибку.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Не принимает параметров (пустые скобки).
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Массив объектов (каждый объект = один товар в корзине).
// Пример элемента: { id: 1, title: "MSI Titan", price: 189900, image: "...", quantity: 2 }
// Если корзина пуста или ошибка — возвращает [] (пустой массив).
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Вызывается из:
//   - getCartCount() — для подсчёта общего количества товаров.
//   - addToCart() — для получения текущего состояния корзины перед добавлением.
//   - saveCartItems() косвенно (через addToCart).
//   - cart.js (loadCart — похожая, но не идентичная логика).
// 
// ЗАДАЧА, КОТОРУЮ РЕШАЕТ:
// Защита от ошибок при работе с localStorage:
// - пользователь мог очистить localStorage;
// - данные могли быть повреждены вручную;
// - старые данные могли иметь другой формат;
// - JSON.parse может упасть на невалидном JSON.
// 
// ОСОБЕННОСТИ РЕАЛИЗАЦИИ:
// - Использует try...catch для перехвата ошибок JSON.parse.
// - Проверяет Array.isArray после парсинга.
// - Никогда не возвращает null/undefined — всегда массив.
// - Использует ранний возврат (early return) для читаемости.
// 
// ВЗАИМОСВЯЗЬ:
// - Использует: localStorage.getItem, JSON.parse, Array.isArray.
// - Вызывается: getCartCount, addToCart (в этом же файле).
// - Аналогичная функция loadCart есть в cart.js (дублирование, но intentional — для изоляции).
function safeParseCart() {
  // Получаем строку из localStorage по ключу CART_STORAGE_KEY ("cart").
  // 
  // ЧТО ТАКОЕ localStorage:
  // localStorage — это встроенное в браузер хранилище "ключ-значение".
  // Данные сохраняются на устройстве пользователя и остаются даже после закрытия вкладки/браузера.
  // Доступно через глобальный объект localStorage (или window.localStorage).
  // 
  // МЕТОД getItem(key):
  // - Принадлежит объекту Storage (localStorage и sessionStorage).
  // - Принимает один параметр: строку — имя ключа.
  // - Возвращает строку (или null, если ключа нет).
  // - Данные хранятся всегда как строки! Даже если вы сохранили число или объект.
  // 
  // Альтернативы:
  // - sessionStorage — данные живут только до закрытия вкладки.
  // - cookies — старый способ, имеют размер ограничения (~4KB), отправляются на сервер.
  // - IndexedDB — более мощное хранилище (объекты, большие объёмы), сложнее в использовании.
  // 
  // ЗАЧЕМ НУЖНО ЗДЕСЬ:
  // Мы хотим восстановить корзину, которую пользователь добавил на предыдущем визите.
  const saved = localStorage.getItem(CART_STORAGE_KEY);

  // Если saved равно null, undefined, пустой строке "" или false (в JS !"" === true) — 
  // значит данных нет (пользователь никогда ничего не добавлял или очистил хранилище).
  // Возвращаем пустой массив сразу (ранний возврат).
  // Это избегает лишних операций и ошибок.
  if (!saved) return [];

  // Пытаемся разобрать строку как JSON.
  // 
  // try...catch — см. объяснение в data.js.
  // Здесь catch без переменной (catch { ... }) — современный синтаксис (ES2019+),
  // когда нам не нужно использовать сам объект ошибки.
  try {
    // JSON.parse(saved) — глобальный метод.
    // Принимает строку, возвращает JavaScript-значение (объект, массив, строку, число и т.д.).
    // Если строка невалидный JSON — бросает SyntaxError.
    // 
    // ЗАЧЕМ:
    // localStorage хранит ТОЛЬКО строки. Когда мы делали saveCartItems, мы вызвали JSON.stringify(cart).
    // Теперь мы делаем обратное преобразование.
    const parsed = JSON.parse(saved);

    // Проверяем, что после парсинга у нас действительно массив.
    // Array.isArray(parsed) — статический метод Array.
    // Возвращает boolean: true если это массив.
    // 
    // Тернарный оператор: если массив — возвращаем parsed, иначе [].
    // Это защита: если кто-то вручную положил в localStorage строку "hello" или число 42,
    // мы не хотим, чтобы приложение сломалось.
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    // Если JSON.parse упал (невалидный JSON) — мы попадаем сюда.
    // Возвращаем пустой массив. Корзина "сбрасывается" в безопасное состояние.
    // Пользователь ничего не потеряет критично (корзина просто будет пустой).
    return [];
  }
}

