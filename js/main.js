// Объявляем константу showToast и сразу присваиваем ей результат выполнения IIFE.
// 
// ЧТО ТАКОЕ IIFE (Immediately Invoked Function Expression):
// Это функция, которая определяется и сразу же вызывается в том же выражении.
// Синтаксис: (function() { ... })()  или  (() => { ... })()
// 
// ЗАЧЕМ ИСПОЛЬЗУЕТСЯ ЗДЕСЬ:
// Мы хотим, чтобы переменная timer была "приватной" — недоступной снаружи.
// Если бы мы написали просто:
//   let timer;
//   const showToast = function(message) { ... use timer ... }
// то любой код на странице мог бы прочитать/изменить window.timer (если бы мы повесили на window).
// 
// IIFE создаёт новую область видимости (scope).
// Переменная timer объявлена внутри IIFE с помощью let — она видна только внутри возвращаемой функции.
// Это классический паттерн "замыкание" (closure) для инкапсуляции состояния.
// 
// ВНУТРИ IIFE:
//   let timer;                    // приватная переменная
//   return function (message) { ... }  // возвращаем функцию, которая "замыкает" timer
// 
// Когда мы пишем const showToast = (() => { ... })();
// showToast становится той самой возвращённой функцией.
// При каждом вызове showToast(...) внутри неё доступен один и тот же timer (благодаря замыканию).
// 
// АЛЬТЕРНАТИВЫ:
// - Можно было бы использовать класс с приватным полем (#timer в современном JS).
// - Можно было бы хранить timer как свойство объекта.
// - Можно было бы использовать WeakMap или Symbol.
// IIFE — самый простой и совместимый способ для этого случая.
const showToast = (() => {
  // Объявляем переменную timer внутри IIFE.
  // Изначально undefined.
  // Она будет хранить ID таймера, возвращённый setTimeout.
  // Нужна, чтобы при показе нового toast мы могли отменить предыдущий таймер скрытия.
  // Это предотвращает ситуацию, когда старое уведомление прячется после того, как уже показалось новое.
  let timer; // Приватное состояние, недоступное снаружи

  // Возвращаем функцию. Именно эта функция и будет присвоена showToast.
  // Она принимает один параметр: message (строка, которую нужно показать).
  return function (message) {
    // Ищем существующий элемент toast на странице.
    // document.querySelector(".toast") — см. объяснение выше.
    let toast = document.querySelector(".toast");

    // Если toast ещё не существует (первый вызов showToast на странице) —
    // мы создаём его динамически.
    if (!toast) {
      // document.createElement(tagName) — метод Document.
      // Создаёт новый элемент DOM в памяти (ещё не добавлен на страницу).
      // Принимает строку — имя тега ("div", "span", "button" и т.д.).
      // Возвращает новый Element.
      // 
      // ЗАЧЕМ СОЗДАВАТЬ ДИНАМИЧЕСКИ:
      // Мы не хотим засорять HTML-разметку элементом, который нужен только для уведомлений.
      // Создаём только когда впервые понадобился.
      toast = document.createElement("div");

      // Устанавливаем CSS-класс. Элемент получит стили из CSS (toast { ... } .toast--show { ... }).
      toast.className = "toast";

      // setAttribute(name, value) — метод Element.
      // Устанавливает атрибут. Здесь role="status" — это ARIA-атрибут для доступности.
      // Скринридеры будут объявлять содержимое этого элемента как статусное сообщение.
      // 
      // ПАРАМЕТРЫ:
      // name — строка имени атрибута.
      // value — строка значения.
      toast.setAttribute("role", "status");

      // document.body.append(child) — метод Element (body — это Element).
      // Добавляет child в конец списка дочерних элементов body.
      // Теперь toast реально появляется в DOM и становится видимым (после добавления класса toast--show).
      // 
      // АЛЬТЕРНАТИВЫ: appendChild, insertBefore, prepend и т.д.
      document.body.append(toast);
    }

    // Устанавливаем текстовое содержимое toast.
    // Даже если toast уже существовал — мы перезаписываем текст (новое сообщение).
    toast.textContent = message;

    // Добавляем CSS-класс "toast--show".
    // 
    // classList — свойство Element, возвращающее DOMTokenList.
    // 
    // МЕТОД classList.add(token):
    // Принадлежит DOMTokenList.
    // Принимает строку — имя класса.
    // Добавляет класс к элементу (если его ещё нет).
    // Браузер применяет соответствующие CSS-правила (обычно анимация появления).
    // 
    // ЗАЧЕМ НУЖЕН КЛАСС, А НЕ СТИЛИ В JS:
    // Отделение логики от представления. Вся анимация и внешний вид описаны в CSS.
    // JS только решает "когда показать/спрятать".
    toast.classList.add("toast--show");

    // ОТМЕНЯЕМ предыдущий таймер скрытия (если он был).
    // 
    // window.clearTimeout(timer):
    // Глобальный метод (на window).
    // Принимает ID таймера, возвращённый ранее setTimeout.
    // Если timer === undefined — clearTimeout просто ничего не делает (безопасно).
    // 
    // Это важно: если пользователь быстро кликает "добавить в корзину" несколько раз,
    // мы не хотим, чтобы предыдущие уведомления скрывались по своим старым таймерам.
    window.clearTimeout(timer);

    // УСТАНАВЛИВАЕМ НОВЫЙ ТАЙМЕР на скрытие через 2400 миллисекунд (2.4 секунды).
    // 
    // window.setTimeout(callback, delay):
    // Глобальный метод.
    // Принимает:
    //   1. callback — функция, которая будет вызвана позже.
    //   2. delay — число миллисекунд (минимум ~4ms в современных браузерах).
    // Возвращает: числовой ID таймера (можно передать в clearTimeout).
    // 
    // setTimeout НЕ блокирует выполнение кода! 
    // Функция showToast завершается сразу. Через 2.4с браузер вызовет переданную стрелочную функцию.
    // 
    // Стрелочная функция () => toast.classList.remove("toast--show"):
    // Убирает класс "toast--show". CSS обычно имеет transition, поэтому элемент плавно исчезает.
    // 
    // ЗАЧЕМ window. перед clearTimeout/setTimeout:
    // Явное указание, что мы используем глобальные методы. В строгом режиме (и в модулях) это рекомендуется.
    // В данном коде автор явно пишет window. для ясности.
    timer = window.setTimeout(() => toast.classList.remove("toast--show"), 2400);
  };
})();

