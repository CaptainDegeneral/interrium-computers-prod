// ФУНКЦИЯ: addToCart(product)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Добавляет товар в корзину (или увеличивает quantity, если товар уже есть).
// Сохраняет изменения, обновляет счётчик в шапке и показывает toast-уведомление.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Один параметр: product — объект товара.
// Ожидаемые свойства: id, title, price, image (и возможно другие).
// id используется для определения "уже есть в корзине".
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Ничего (побочные эффекты: изменение localStorage, DOM, показ уведомления).
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Это ЦЕНТРАЛЬНАЯ функция добавления в корзину.
// Вызывается из:
//   - catalog.js (при клике на кнопку "В корзину" в карточке товара).
//   - product.js (при клике на кнопку "В корзину" на странице товара).
// 
// ЗАДАЧА:
// Единая точка входа для добавления товаров. Гарантирует, что:
// - логика "если уже есть — увеличить количество" всегда одна и та же;
// - сохранение, обновление бейджа и уведомление всегда происходят.
// 
// ОСОБЕННОСТИ:
// - Использует .find() для поиска существующего товара.
// - Number(...) для безопасного сравнения id (id могут приходить как строка из dataset или число).
// - Создаёт новый объект при добавлении (не мутирует оригинальный product).
// - Вызывает три другие функции: saveCartItems, updateCartBadge, showToast.
function addToCart(product) {
  // Загружаем текущее состояние корзины из localStorage.
  const cart = safeParseCart();

  // Ищем, есть ли уже товар с таким же id в корзине.
  // 
  // Array.prototype.find(callback):
  // Метод массива.
  // Принимает callback, который вызывается для каждого элемента.
  // Возвращает первый элемент, для которого callback вернул truthy значение.
  // Если ничего не найдено — возвращает undefined.
  // 
  // Стрелочная функция (item) => Number(item.id) === Number(product.id):
  // Для каждого item в cart сравниваем его id с id переданного product.
  // Number(...) — приводим к числу, потому что:
  //   - в JSON id обычно число;
  //   - в dataset.addCart (HTML) id приходит как строка.
  // Сравнение 1 === "1" в JS даёт false, поэтому Number обязателен.
  // 
  // ЗАЧЕМ НУЖЕН find:
  // Мы не хотим добавлять один и тот же товар второй строкой в корзину.
  // Вместо этого увеличиваем quantity существующей записи.
  const existing = cart.find((item) => Number(item.id) === Number(product.id));

  // Если existing не undefined (товар уже был) —
  if (existing) {
    // Увеличиваем его quantity на 1.
    // existing.quantity += 1; — мутирует объект внутри массива cart.
    // Это работает, потому что объекты в JS передаются по ссылке.
    // cart[индекс] и existing указывают на один и тот же объект в памяти.
    existing.quantity += 1;
  } else {
    // Если товара не было — добавляем новый объект в конец массива.
    // 
    // Array.prototype.push(element):
    // Добавляет один или несколько элементов в конец массива.
    // Изменяет оригинальный массив (мутирует).
    // Возвращает новую длину массива.
    // 
    // Мы создаём НОВЫЙ объект { id, title, price, image, quantity: 1 }.
    // Копируем только нужные поля из product.
    // Не копируем всё (например, specs, category) — они не нужны в корзине.
    // quantity всегда начинается с 1.
    cart.push({
      id: product.id,
      title: product.title,
      price: product.price,
      image: product.image,
      quantity: 1,
    });
  }

  // Сохраняем изменённый массив cart обратно в localStorage.
  saveCartItems(cart);

  // Обновляем красный бейдж в шапке (количество товаров).
  // Комментарий в оригинале: "Вызываем напрямую, без window."
  updateCartBadge(); // Вызываем напрямую, без window.

  // Показываем пользователю красивое уведомление "Товар добавлен в корзину".
  // showToast создаст/обновит toast-элемент и через 2.4с скроет его.
  showToast("Товар добавлен в корзину");
}

