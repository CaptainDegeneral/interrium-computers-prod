// ФУНКЦИЯ: getCartCount()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Подсчитывает общее количество товаров в корзине (с учётом quantity каждого товара).
// Например, если в корзине два товара по 3 штуки — вернёт 6.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Ничего.
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Число (number) — сумма всех quantity.
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Вызывается из updateCartBadge() для отображения числа в шапке (красный кружочек).
// Также используется в cart.js (getCartCountLocal — похожая реализация).
// 
// ЗАДАЧА:
// Дать быстрое число "сколько всего позиций в корзине" для UI.
// 
// ОСОБЕННОСТИ:
// - Использует Array.prototype.reduce() — мощный метод для свёртки массива в одно значение.
// - Number(item.quantity || 0) — защита: если quantity отсутствует или не число, берём 0.
function getCartCount() {
  // Вызываем safeParseCart(), получаем текущий массив корзины.
  // Затем вызываем на нём метод .reduce().
  // 
  // МЕТОД Array.prototype.reduce(callback, initialValue):
  // Принадлежит прототипу Array.
  // Используется для "сворачивания" (reduce) массива к одному значению.
  // 
  // ПАРАМЕТРЫ:
  // 1. callback — функция, которая вызывается для каждого элемента.
  //    Получает 4 аргумента: (accumulator, currentValue, index, array).
  //    Должна возвращать новое значение accumulator для следующей итерации.
  // 2. initialValue (необязательный) — начальное значение accumulator.
  // 
  // КАК РАБОТАЕТ ЗДЕСЬ:
  // initialValue не передан явно — будет использован первый элемент массива.
  // Но мы передаём стрелочную функцию, которая принимает (sum, item).
  // sum — это аккумулятор (накапливаемая сумма).
  // item — текущий элемент массива.
  // 
  // Внутри: sum + Number(item.quantity || 0)
  // На каждой итерации мы добавляем quantity текущего товара к накопленной сумме.
  // В конце reduce возвращает финальную сумму.
  // 
  // ПРИМЕР:
  // cart = [{quantity: 2}, {quantity: 3}]
  // reduce → (0 + 2) → (2 + 3) → возвращает 5
  // 
  // АЛЬТЕРНАТИВЫ:
  // Можно было бы использовать for...of цикл или forEach + внешняя переменная.
  // reduce считается более "функциональным" и компактным.
  // 
  // ЗАЧЕМ ЗДЕСЬ:
  // Нам нужно одно число из массива объектов. reduce — идеальный инструмент.
  return safeParseCart().reduce((sum, item) => sum + Number(item.quantity || 0), 0);
}

