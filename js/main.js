// ФУНКЦИЯ: updateCartBadge()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Находит в DOM элемент с классом .header__cart-count и обновляет его текстовое содержимое
// на текущее общее количество товаров в корзине.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// Ничего.
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Ничего (побочный эффект — изменение DOM).
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// Вызывается:
//   - При загрузке страницы (в DOMContentLoaded).
//   - После добавления товара в корзину (addToCart).
//   - После изменения количества/удаления в корзине (cart.js).
//   - После очистки корзины.
// 
// ЗАДАЧА:
// Синхронизировать визуальный счётчик в шапке сайта с реальным состоянием корзины.
// Пользователь всегда видит актуальное число, не заходя в корзину.
// 
// ОСОБЕННОСТИ:
// - Использует document.querySelector — поиск по CSS-селектору.
// - Проверка if (badge) — защита, если элемента нет на странице (некоторые страницы могут не иметь шапки).
// - String(...) — явное приведение числа к строке (хотя textContent и так приводит).
function updateCartBadge() {
  // document.querySelector(selector) — метод глобального объекта Document (DOM API).
  // 
  // ЧТО ТАКОЕ DOM (Document Object Model):
  // Когда браузер загружает HTML-страницу, он разбирает её и строит в памяти древовидную структуру —
  // модель документа. Каждый HTML-тег становится объектом (Node/Element).
  // JavaScript может читать и изменять эту модель через DOM API.
  // 
  // querySelector — один из способов поиска элементов в этой модели.
  // Принимает один параметр: строку CSS-селектора (".header__cart-count", "#id", "div > p" и т.д.).
  // Возвращает: первый найденный Element (или null, если ничего не найдено).
  // 
  // АЛЬТЕРНАТИВЫ:
  // - getElementById('id') — быстрее, но только по id.
  // - getElementsByClassName('class') — возвращает живую коллекцию (HTMLCollection).
  // - querySelectorAll — возвращает все совпадения (NodeList, статическая).
  // querySelector — самый универсальный и удобный для современных проектов.
  // 
  // ЗАЧЕМ ЗДЕСЬ:
  // Нам нужно найти конкретный <span class="header__cart-count">0</span> в шапке.
  const badge = document.querySelector(".header__cart-count");

  // Проверяем, нашли ли мы элемент.
  // Если badge === null (элемента нет на странице) — просто выходим из функции (ранний возврат).
  // Это важно: на некоторых страницах или в тестах шапки может не быть.
  // Без проверки мы бы получили ошибку при попытке badge.textContent = ...
  if (badge) {
    // Вызываем getCartCount() — получаем число.
    // String(число) — явно превращаем число в строку.
    // 
    // СВОЙСТВО Element.prototype.textContent:
    // Принадлежит элементам DOM.
    // При чтении — возвращает весь текст внутри элемента (и вложенных).
    // При записи — заменяет всё содержимое элемента на переданную строку (удаляет предыдущие дочерние узлы).
    // 
    // badge.textContent = "5"; — браузер обновит отображаемый текст в этом span на "5".
    // Пользователь сразу увидит изменение (без перезагрузки).
    badge.textContent = String(getCartCount());
  }
}

