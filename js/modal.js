// ═══════════════════════════════════════════════════════════════════════════════
// МОДУЛЬ: modal.js
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ СУЩНОСТИ:
// Этот файл содержит универсальную логику работы со всеми модальными окнами (модалками) на сайте
// и клиентскую валидацию форм внутри этих модалок (и не только).
// 
// Модальные окна — это всплывающие поверх страницы "окошки", которые блокируют взаимодействие
// с основным контентом до закрытия (оверлей + затемнение).
// 
// Функциональность:
// 1. Открытие модальных окон по клику на элементы с атрибутом data-modal="idМодалки".
// 2. Закрытие модалок по:
//    - клику на оверлей (фон);
//    - клику на элемент с data-modal-close;
//    - нажатию клавиши Escape;
//    - автоматически после успешной отправки формы (с таймаутом).
// 3. Блокировка прокрутки body (класс is-locked) при открытой модалке.
// 4. Обновление ARIA-атрибутов (aria-hidden) для доступности.
// 5. Полноценная клиентская валидация форм:
//    - Проверка обязательных полей (required).
//    - Специфические правила для email и телефона.
//    - Показ/скрытие сообщений об ошибках под полями.
//    - Очистка ошибок при фокусе/вводе.
// 6. Обработка успешной валидации: показ экрана успеха внутри модалки или просто сброс формы + toast.
// 
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// - Подключается на ВСЕХ страницах сайта (index.html, catalog.html, cart.html, product.html, about.html, contacts.html).
// - Используется для модалки "Оставить заявку" (requestModal) на каждой странице.
// - Формы с классом .js-validate-form автоматически получают валидацию.
// - Вызывает глобальную showToast из main.js при успехе вне модалки.
// - Не зависит от других модулей (catalog, cart, product) — полностью универсальный.
// 
// ЗАДАЧА, КОТОРУЮ РЕШАЕТ:
// - Единообразная работа всех модальных окон без дублирования кода на каждой странице.
// - Улучшение UX: пользователь не теряет контекст, может быстро оставить заявку с любой страницы.
// - Клиентская валидация даёт мгновенную обратную связь (без ожидания сервера).
// - Доступность (ARIA, клавиатура).
// 
// ОСОБЕННОСТИ РЕАЛИЗАЦИИ:
// - Делегирование событий на document (initModal) — не нужно знать все модалки заранее.
// - Отдельные функции для открытия/закрытия (открытые для переиспользования).
// - Валидация полностью на клиенте, без сетевых запросов.
// - Использует свойство .hidden (HTML attribute) для показа/скрытия экрана успеха.
// - setTimeout для автоматического закрытия после успеха.
// - Много ранних возвратов (if (!element) return).
// - Поддержка как модалок с success-экраном, так и обычных форм.
// 
// ВЗАИМОСВЯЗЬ С ДРУГИМИ ЧАСТЯМИ:
// - Предоставляет: openModal, closeModal (хотя обычно используются через data-атрибуты).
// - Зависит от: showToast (main.js), DOM, document.addEventListener.
// - HTML-разметка модалок всегда одинаковая (см. все .html файлы — копипаст блока .modal#requestModal).
// - CSS (modal стили в style.css или отдельных) отвечает за .is-open, .is-locked и т.д.
// - Формы в модалках имеют класс js-validate-form + required инпуты.
// 
// УРОВЕНЬ ДЕТАЛИЗАЦИИ ДЛЯ СТУДЕНТОВ:
// Комментарии объясняют:
// - что такое модальное окно и зачем оно нужно;
// - делегирование событий (event delegation);
// - ARIA-атрибуты и доступность;
// - клиентская валидация vs серверная;
// - как работает preventDefault на submit;
// - разницу между .hidden, display:none, visibility;
// - работу с closest() для поиска родителей;
// - регулярные выражения в упрощённом виде (replace(/\D/g, '')).
// ═══════════════════════════════════════════════════════════════════════════════

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: getFieldMessage(input)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Определяет, есть ли ошибка валидации в конкретном поле формы, и возвращает текст сообщения об ошибке.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// input — DOM-элемент <input> или <textarea>.
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Строка:
//   - Если поле пустое и required — "Имя: заполните поле" (берёт название из label).
//   - Для email: "Email: укажите корректный адрес" (простая проверка на @ и .).
//   - Для phone: "Телефон: укажите не менее 10 цифр" (убирает всё не-цифры и считает длину).
//   - Если всё ок — пустая строка "".
// 
// КАК ИСПОЛЬЗУЕТСЯ:
// Вызывается из validateForm() для каждого required поля.
// 
// ОСОБЕННОСТИ:
// - Использует .closest() для поиска родительского .form__field и его первого текстового узла (название поля).
// - Простые эвристические проверки (не настоящая валидация email по RFC).
// - Специально обрабатывает name="email" и name="phone".
function getFieldMessage(input) {
  // Получаем значение поля, убирая пробелы по краям.
  // .trim() — метод String.
  const value = input.value.trim();

  // Ищем ближайший родительский элемент с классом .form__field.
  // .closest(selector) — поднимается вверх по DOM, пока не найдёт совпадение.
  const label = input.closest('.form__field');

  // Если нашли label — берём текст первого дочернего текстового узла (это обычно "Имя", "Телефон" и т.д.).
  // label.firstChild.textContent — firstChild может быть текстовым узлом перед <input>.
  // Если не нашли — fallback "Поле".
  const fieldName = label ? label.firstChild.textContent.trim() : 'Поле';

  // Если после trim значение пустое — это ошибка обязательного поля.
  if (!value) {
    // Шаблонная строка с названием поля.
    return `${fieldName}: заполните поле`;
  }

  // Специальная проверка для email (по атрибуту name, а не по type).
  // Простейшая эвристика: должна содержать @ И точку.
  // Это НЕ полноценная валидация email (для этого нужны сложные regex или библиотека).
  if (input.name === 'email' && (!value.includes('@') || !value.includes('.'))) {
    return 'Email: укажите корректный адрес';
  }

  // Специальная проверка для телефона.
  // value.replace(/\D/g, '') — убирает все НЕ-цифровые символы (регулярное выражение).
  // \D — "не цифра", g — global (все вхождения).
  // .length — длина оставшейся строки цифр.
  // Если меньше 10 цифр — ошибка.
  if (input.name === 'phone' && value.replace(/\D/g, '').length < 10) {
    return 'Телефон: укажите не менее 10 цифр';
  }

  // Если дошли сюда — поле валидно.
  return '';
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: clearFieldError(input)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Удаляет визуальную ошибку с поля (убирает класс field--error и элемент .error-message).
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// input — поле формы.
// 
// КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
// Ничего (побочный эффект на DOM).
function clearFieldError(input) {
  // Находим ближайший .form__field.
  const field = input.closest('.form__field');
  if (!field) return;

  // Удаляем класс, который обычно делает поле красным (CSS).
  field.classList.remove('field--error');

  // Ищем внутри field элемент с классом .error-message.
  const error = field.querySelector('.error-message');
  if (error) {
    // .remove() — современный способ удалить элемент из DOM.
    error.remove();
  }
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: showFieldError(input, message)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Показывает сообщение об ошибке под конкретным полем.
// Сначала очищает предыдущую ошибку, затем добавляет класс и новый <span class="error-message">.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// input — поле.
// message — текст ошибки.
// 
// ВОЗВРАЩАЕТ:
// Ничего.
function showFieldError(input, message) {
  const field = input.closest('.form__field');
  if (!field) return;

  // Сначала убираем старую ошибку (если была).
  clearFieldError(input);

  // Добавляем класс ошибки (для стилей).
  field.classList.add('field--error');

  // Создаём новый элемент <span>.
  const error = document.createElement('span');
  error.className = 'error-message';
  error.textContent = message;

  // Добавляем span внутрь .form__field (после label/input).
  field.append(error);
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: validateForm(form)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Проверяет всю форму на валидность.
// Для каждого required поля вызывает getFieldMessage.
// Если есть ошибки — показывает их и возвращает false.
// Если всё хорошо — возвращает true.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// form — элемент <form>.
// 
// ВОЗВРАЩАЕТ:
// boolean — можно ли отправлять форму.
function validateForm(form) {
  // Находим все input и textarea с атрибутом required внутри формы.
  // querySelectorAll возвращает NodeList.
  const fields = form.querySelectorAll('input[required], textarea[required]');

  // Флаг "форма валидна".
  let isValid = true;

  // Для каждого обязательного поля:
  fields.forEach((input) => {
    // Получаем сообщение (или "").
    const message = getFieldMessage(input);

    if (message) {
      // Есть ошибка — показываем её.
      showFieldError(input, message);
      // Помечаем форму как невалидную.
      isValid = false;
    }
  });

  return isValid;
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: handleFormSuccess(form)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Обрабатывает успешную отправку формы (после валидации).
// Если форма внутри модального окна — показывает экран успеха (.form-success),
// через 2.2 секунды закрывает модалку и сбрасывает форму.
// Если форма не в модалке — просто сбрасывает и показывает toast.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// form — форма, которая прошла валидацию.
// 
// ВОЗВРАЩАЕТ:
// Ничего.
function handleFormSuccess(form) {
  // Пытаемся найти ближайшее .modal__window (родительский контейнер модалки).
  const modalWindow = form.closest('.modal__window');

  if (modalWindow) {
    // Мы внутри модалки.
    // Ищем элемент успеха внутри того же modal__window.
    const success = modalWindow.querySelector('.form-success');

    // Прячем форму (свойство .hidden = true добавляет атрибут hidden).
    form.hidden = true;

    if (success) {
      success.hidden = false; // показываем блок "Спасибо! Заявка принята."
    }

    // Через 2200 мс автоматически закрываем модалку и возвращаем форму в исходное состояние.
    window.setTimeout(() => {
      const modal = form.closest('.modal');
      if (modal) {
        closeModal(modal.id);
      }
      form.reset();           // сбрасывает все поля формы
      form.hidden = false;    // показываем форму обратно
      if (success) {
        success.hidden = true;
      }
    }, 2200);

    return; // выходим, чтобы не выполнять код ниже
  }

  // Если форма НЕ внутри модалки (например, на contacts.html) —
  // просто сбрасываем и показываем toast.
  form.reset();
  showToast('Спасибо! Заявка принята.');
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: openModal(id)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Открывает модальное окно по его id.
// Добавляет класс .is-open, устанавливает aria-hidden="false", блокирует body.
// 
// КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
// id — строка, id модального элемента (например, "requestModal").
// 
// ВОЗВРАЩАЕТ:
// Ничего.
function openModal(id) {
  // document.getElementById — быстрый поиск по id.
  const modal = document.getElementById(id);
  if (!modal) return;

  modal.classList.add('is-open');
  modal.setAttribute('aria-hidden', 'false');
  document.body.classList.add('is-locked');
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: closeModal(id)
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Закрывает модальное окно по id.
// Убирает классы и атрибуты.
function closeModal(id) {
  const modal = document.getElementById(id);
  if (!modal) return;

  modal.classList.remove('is-open');
  modal.setAttribute('aria-hidden', 'true');
  document.body.classList.remove('is-locked');
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: initModal()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Настраивает глобальные обработчики для открытия и закрытия всех модалок через data-атрибуты.
// Использует делегирование на document — работает для любых модалок, даже добавленных позже.
// 
// ВЫЗЫВАЕТСЯ:
// Из DOMContentLoaded внизу файла.
function initModal() {
  // Один слушатель click на всём документе.
  document.addEventListener('click', (event) => {
    // Ищем, был ли клик на элементе (или внутри), у которого есть data-modal.
    // data-modal="requestModal" — открывает модалку с таким id.
    const opener = event.target.closest('[data-modal]');
    if (opener) {
      openModal(opener.dataset.modal); // dataset.modal даёт значение атрибута
    }

    // Ищем клик на элементе с data-modal-close (обычно крестик или оверлей).
    const closer = event.target.closest('[data-modal-close]');
    if (closer) {
      // Находим ближайшую .modal вверх по дереву.
      const modal = closer.closest('.modal');
      if (modal) {
        closeModal(modal.id);
      }
    }
  });

  // Глобальный обработчик Escape — закрывает ВСЕ открытые модалки.
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
      // querySelectorAll возвращает все открытые модалки.
      // forEach — закрываем каждую.
      document.querySelectorAll('.modal.is-open').forEach((modal) => closeModal(modal.id));
    }
  });
}

// ═══════════════════════════════════════════════════════════════════════════════
// ФУНКЦИЯ: initFormValidation()
// ═══════════════════════════════════════════════════════════════════════════════
// 
// НАЗНАЧЕНИЕ:
// Находит все формы с классом .js-validate-form и настраивает на них:
// - submit: preventDefault + validateForm + handleFormSuccess.
// - focus и input на полях: очистка предыдущих ошибок.
// 
// Делает валидацию "живой".
function initFormValidation() {
  // Находим все такие формы (их может быть несколько: в модалке и на странице контактов).
  document.querySelectorAll('.js-validate-form').forEach((form) => {
    // При отправке формы:
    form.addEventListener('submit', (event) => {
      // Останавливаем стандартное поведение браузера (отправку на сервер / перезагрузку).
      // Это критично — мы делаем всё на клиенте.
      event.preventDefault();

      // Если валидация прошла — обрабатываем успех.
      if (validateForm(form)) {
        handleFormSuccess(form);
      }
    });

    // Для каждого input/textarea внутри формы подписываемся на focus и input.
    // При любом взаимодействии — убираем красную ошибку (пользователь начал исправлять).
    form.querySelectorAll('input, textarea').forEach((input) => {
      input.addEventListener('focus', () => clearFieldError(input));
      input.addEventListener('input', () => clearFieldError(input));
    });
  });
}

