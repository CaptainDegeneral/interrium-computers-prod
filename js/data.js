// НАЗНАЧЕНИЕ СУЩНОСТИ:
// Этот файл (модуль) содержит единственную асинхронную функцию loadProducts(), 
// которая отвечает за загрузку данных о товарах (компьютерах) из внешнего JSON-файла.
// Модуль является центральным источником данных для всего проекта: 
// - каталог (catalog.js) использует его для отображения списка товаров;
// - страница отдельного товара (product.js) использует его для загрузки конкретного товара по ID;
// - другие части проекта (main.js, cart.js и т.д.) косвенно зависят от этих данных через addToCart().
//
// КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
// 1. Вызывается из initCatalog() в catalog.js при загрузке страницы каталога.
// 2. Вызывается из initProductPage() в product.js при загрузке страницы товара.
// 3. Результат (массив объектов товаров) сохраняется в переменные allProducts и currentProduct.
// 4. Данные передаются в функции добавления в корзину (addToCart из main.js).
//
// ЗАДАЧА, КОТОРУЮ РЕШАЕТ:
// Обеспечивает отделение данных от логики отображения (принцип разделения ответственности).
// Позволяет легко заменить источник данных (файл JSON → API) без изменения остального кода.
// Обрабатывает ошибки сети/файла gracefully, показывая пользователю понятное сообщение.
//
// ОСОБЕННОСТИ РЕАЛИЗАЦИИ:
// - Использует современный async/await (асинхронный синтаксис) вместо старых колбэков.
// - Делает HTTP-запрос с помощью fetch() — встроенного в браузер метода.
// - Проверяет успешность ответа (response.ok).
// - Преобразует ответ в JavaScript-объект с помощью response.json().
// - Гарантирует, что всегда возвращает массив (даже при ошибке возвращает []).
// - Показывает toast-уведомление при ошибке (использует showToast из main.js — глобальная функция).
// - Не хранит данные внутри себя — просто возвращает их вызывающему коду.
//
// ВЗАИМОСВЯЗЬ С ДРУГИМИ ЧАСТЯМИ ПРОЕКТА:
// - Зависит от: fetch (браузерный API), JSON-файла data/products.json, showToast (из main.js).
// - Используется: catalog.js (initCatalog), product.js (initProductPage).
// - Не зависит от DOM напрямую (кроме косвенного вызова showToast).
// - Данные из этого модуля попадают в корзину через addToCart (main.js).
//
// УРОВЕНЬ ДЕТАЛИЗАЦИИ ДЛЯ СТУДЕНТОВ:
// Ниже в комментариях к каждой строке и блоку подробно объясняется:
// - что такое асинхронность;
// - что такое Promise;
// - как работает fetch;
// - что такое JSON;
// - почему важно обрабатывать ошибки;
// - как браузер выполняет этот код;
// - какие альтернативы существуют (XMLHttpRequest, axios и т.д.).
// ═══════════════════════════════════════════════════════════════════════════════

/**
 * Асинхронная функция загрузки списка товаров из JSON-файла.
 * 
 * НАЗНАЧЕНИЕ:
 * Загружает данные о всех доступных компьютерах (товарах) из файла data/products.json.
 * Возвращает массив объектов, где каждый объект описывает один товар 
 * (свойства: id, title, brand, price, image, stock, category, specs и т.д.).
 * 
 * КАКИЕ ДАННЫЕ ПРИНИМАЕТ:
 * Не принимает никаких параметров (пустые круглые скобки ()).
 * 
 * КАКИЕ ДАННЫЕ ВОЗВРАЩАЕТ:
 * Promise, который разрешается (resolves) в массив объектов товаров.
 * Если загрузка успешна — возвращает массив (даже если в файле был не массив, возвращает []).
 * Если произошла ошибка (сеть, файл не найден, сервер вернул ошибку) — 
 * показывает уведомление пользователю и возвращает пустой массив [].
 * 
 * КАК ИСПОЛЬЗУЕТСЯ В ПРОЕКТЕ:
 * Вызывается с помощью await в двух местах:
 *   1. В catalog.js: allProducts = await loadProducts(); затем товары отрисовываются.
 *   2. В product.js: const products = await loadProducts(); затем ищется товар по id.
 * 
 * ЗАДАЧА, КОТОРУЮ РЕШАЕТ:
 * Получить актуальные данные о товарах без перезагрузки страницы.
 * Сделать данные доступными для нескольких страниц проекта.
 * Обработать возможные проблемы при загрузке, чтобы сайт не "падал".
 * 
 * ОСОБЕННОСТИ РЕАЛИЗАЦИИ:
 * - async function — делает функцию асинхронной (может использовать await внутри).
 * - await fetch(...) — приостанавливает выполнение до получения ответа от сервера.
 * - await response.json() — приостанавливает до полного разбора JSON.
 * - try...catch — ловит любые ошибки, которые могут возникнуть при работе с сетью.
 * - Array.isArray(data) — проверка, что данные действительно массив (защита от ошибок в файле).
 * - showToast(...) — вызывает глобальную функцию из main.js для показа всплывающего сообщения.
 * 
 * ВЗАИМОСВЯЗЬ С ДРУГИМИ ЧАСТЯМИ:
 * - Вызывает: fetch (браузер), JSON.parse (внутри response.json), showToast (main.js).
 * - Используется: catalog.js, product.js.
 * - Файл data/products.json — источник правды для всех товаров.
 */

// Объявляем асинхронную функцию с именем loadProducts.
// Ключевое слово "async" перед function означает, что функция будет возвращать Promise
// и внутри неё можно использовать ключевое слово "await" для ожидания асинхронных операций.
// Без "async" мы не смогли бы использовать await, и код стал бы сложнее (пришлось бы писать .then()).
async function loadProducts() {
  // Блок try...catch — это конструкция для обработки ошибок.
  // Код внутри try выполняется "в надежде на успех".
  // Если в любой строке внутри try произойдёт ошибка (exception), 
  // выполнение try прерывается и управление передаётся в блок catch.
  // Это нужно, потому что сетевые запросы могут падать по многим причинам:
  // нет интернета, сервер не отвечает, файл удалён, CORS-ошибка и т.д.
  try {
    // Выполняем HTTP-запрос к файлу 'data/products.json' с помощью встроенного браузерного метода fetch.
    // 
    // ЧТО ТАКОЕ fetch:
    // fetch — это современный (с 2015 года, Fetch API) способ делать сетевые запросы из JavaScript в браузере.
    // Альтернатива старому XMLHttpRequest (XHR).
    // fetch(url) отправляет GET-запрос по указанному адресу и сразу возвращает Promise.
    // 
    // ЧТО ТАКОЕ PROMISE:
    // Promise (обещание) — это объект, представляющий результат асинхронной операции,
    // который может быть в одном из трёх состояний:
    //   - pending (в ожидании) — операция ещё не завершена;
    //   - fulfilled (выполнено успешно);
    //   - rejected (отклонено с ошибкой).
    // 
    // fetch возвращает Promise, потому что запрос по сети занимает время (миллисекунды или секунды),
    // и мы не хотим "замораживать" весь сайт на это время (блокирующий вызов).
    // 
    // Ключевое слово "await" перед fetch(...) означает:
    // "Приостанови выполнение этой функции до тех пор, пока Promise не разрешится.
    // Когда ответ придёт — продолжай выполнение, и результат (Response-объект) положи в переменную response".
    // 
    // Параметр: строка с относительным путём к JSON-файлу (относительно текущей HTML-страницы).
    // Возвращает: Promise<Response>, где Response — специальный объект с информацией об ответе сервера.
    const response = await fetch('data/products.json');

    // Проверяем, был ли ответ от сервера успешным.
    // 
    // response.ok — это свойство объекта Response.
    // Оно равно true, если HTTP-статус ответа в диапазоне 200–299 (успешные коды).
    // false — для 404 (не найдено), 500 (ошибка сервера), 403 (запрещено) и т.д.
    // 
    // ЗАЧЕМ ЭТА ПРОВЕРКА НУЖНА:
    // fetch() НЕ бросает ошибку автоматически при HTTP-ошибках (4xx, 5xx).
    // Он считает "успехом" любое завершение соединения.
    // Поэтому мы обязаны сами проверять status.
    // 
    // Если не ок — мы вручную бросаем (throw) новую ошибку.
    // Это заставит выполнение перейти в блок catch.
    // 
    // throw new Error(...) — создаёт объект ошибки с сообщением и "выбрасывает" его.
    // Сообщение на русском, чтобы потом можно было показать пользователю.
    if (!response.ok) {
      throw new Error('Не удалось загрузить товары');
    }

    // Преобразуем тело ответа из JSON-строки в JavaScript-объект (или массив).
    // 
    // ЧТО ТАКОЕ JSON:
    // JSON (JavaScript Object Notation) — текстовый формат обмена данными.
    // Выглядит почти как JavaScript-объект: {"id":1,"title":"MSI"}.
    // Но это просто текст. Браузер/сервер передаёт именно текст.
    // 
    // response.json() — метод объекта Response.
    // Он читает тело ответа как текст, затем вызывает JSON.parse() для превращения в объект.
    // Возвращает Promise, поэтому мы используем await.
    // 
    // await здесь снова приостанавливает функцию до полного разбора.
    // После этого в переменную data попадёт готовый JavaScript-массив или объект.
    // 
    // Параметров нет.
    // Возвращает: Promise<any> (обычно массив объектов или объект).
    const data = await response.json();

    // Проверяем, является ли полученный data массивом.
    // 
    // Array.isArray(data) — статический метод глобального объекта Array.
    // Возвращает true, если переданное значение является массивом, иначе false.
    // 
    // ЗАЧЕМ НУЖНА ЭТА ПРОВЕРКА:
    // Файл products.json теоретически может содержать не массив, а объект или строку.
    // Или сервер может вернуть ошибку в формате {error: "..."}.
    // Мы хотим защитить остальной код от неожиданных типов данных.
    // Если это не массив — возвращаем пустой массив, чтобы сайт продолжал работать.
    // 
    // Тернарный оператор: условие ? значение_если_истина : значение_если_ложь
    // Это короткая форма if-else.
    return Array.isArray(data) ? data : [];
  } catch (error) {
    // Блок catch выполняется, если:
    // - произошла ошибка сети (fetch не смог соединиться);
    // - response.ok был false (мы бросили Error);
    // - response.json() не смог разобрать ответ (невалидный JSON);
    // - любая другая синхронная ошибка внутри try.
    // 
    // Переменная error — это объект ошибки, который был "пойман".
    // В нём есть свойства: message, stack и т.д. (можно вывести в console.error).
    // 
    // В нашем случае мы НЕ логируем ошибку подробно (чтобы не пугать пользователя),
    // а показываем красивое уведомление через showToast.
    // 
    // showToast — это функция, объявленная в main.js.
    // Она глобально доступна, потому что скрипт main.js подключается раньше data.js на страницах.
    // Параметр: строка сообщения.
    // showToast создаёт или находит div.toast и показывает его на 2.4 секунды.
    showToast('Товары временно недоступны');

    // В случае любой ошибки возвращаем пустой массив.
    // Это критично для стабильности:
    // - catalog.js получит [], отрисует "Товары не найдены".
    // - product.js получит [], не найдёт товар и перенаправит на catalog.html.
    // Сайт не падает, пользователь видит понятное сообщение.
    return [];
  }
}
